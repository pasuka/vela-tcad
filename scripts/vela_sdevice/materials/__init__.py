def varshni_gap(eg0: float, alpha: float, beta: float, tpar: float, temperature_K: float) -> Tuple[float, float]:
    """Return ``(Eg(T), Eg(0))`` for Sentaurus' ``Bandgap`` law.

    ``Eg(T) = Eg0 + alpha Tpar^2/(beta+Tpar) - alpha T^2/(beta+T)``; ``Eg0`` is
    defined at ``Tpar`` and ``Eg(0)`` is the zero-temperature gap the electron
    mass law refers to.
    """
    if beta + tpar <= 0.0 or beta + temperature_K <= 0.0:
        raise ValueError("Varshni denominators must be positive")
    eg_zero = eg0 + alpha * tpar * tpar / (beta + tpar)
    eg_T = eg_zero - alpha * temperature_K * temperature_K / (beta + temperature_K)
    return eg_T, eg_zero


def dos_prefactor_cm3(temperature_K: float, mass_ratio: float = 1.0) -> float:
    """``2 (2 pi m kB T / h^2)^{3/2}`` in cm^-3 for ``m = mass_ratio * m0``."""
    m = mass_ratio * CONSTANTS["m0_kg"]
    value_m3 = 2.0 * (2.0 * math.pi * m * CONSTANTS["kb_J_per_K"] * temperature_K / CONSTANTS["h_J_s"] ** 2) ** 1.5
    return value_m3 / 1.0e6


def electron_dos_mass(a: float, ml: float, mm: float, eg_zero: float, eg_T: float) -> float:
    """Formula 1: ``me/m0 = [(6 mt)^2 ml]^{1/3} + mm`` with ``mt = a Eg(0)/Eg(T)``."""
    if eg_T <= 0.0:
        raise ValueError("Eg(T) must be positive for the electron mass law")
    mt = a * eg_zero / eg_T
    return ((6.0 * mt) ** 2 * ml) ** (1.0 / 3.0) + mm


def hole_dos_mass(coefficients: Dict[str, float], temperature_K: float) -> float:
    """Formula 1: ``mh/m0 = [(a+bT+cT^2+dT^3+eT^4)/(1+fT+gT^2+hT^3+iT^4)]^{2/3} + mm``."""
    T = temperature_K
    numerator = sum(coefficients.get(k, 0.0) * T ** i for i, k in enumerate(("a", "b", "c", "d", "e")))
    denominator = 1.0 + sum(coefficients.get(k, 0.0) * T ** (i + 1) for i, k in enumerate(("f", "g", "h", "i")))
    if denominator <= 0.0 or numerator < 0.0:
        raise ValueError("hole mass law ratio must be non-negative")
    return (numerator / denominator) ** (2.0 / 3.0) + coefficients.get("mm", 0.0)


def intrinsic_density_cm3(nc_cm3: float, nv_cm3: float, effective_gap_eV: float, temperature_K: float) -> float:
    kT = KB_EV_PER_K * temperature_K
    return math.sqrt(nc_cm3 * nv_cm3) * math.exp(-effective_gap_eV / (2.0 * kT))


def evaluate_semiconductor(sections: Dict[str, Dict[str, Any]], temperature_K: float,
                           fold_old_slotboom: bool) -> Dict[str, Any]:
    """Evaluate the frozen material scalars from merged section parameter maps.

    ``sections[section][name]`` is a list of numbers (``dEg0`` variants are
    keyed as ``dEg0(<variant>)``).  Returns the C3 fields in cm/eV units plus
    a ``derivation`` block with every intermediate value.
    """
    bandgap = sections.get("Bandgap", {})
    e_dos = sections.get("eDOSMass", {})
    h_dos = sections.get("hDOSMass", {})
    for name in ("Eg0", "alpha", "beta", "Tpar", "Chi0"):
        if name not in bandgap:
            raise KeyError(f"Bandgap.{name}")
    eg_T, eg_zero = varshni_gap(bandgap["Eg0"][0], bandgap["alpha"][0], bandgap["beta"][0],
                                bandgap["Tpar"][0], temperature_K)
    if _formula(e_dos) != 1 or _formula(h_dos) != 1:
        raise ValueError("DOS Formula 1 required")
    for name in ("a", "ml", "mm"):
        if name not in e_dos:
            raise KeyError(f"eDOSMass.{name}")
    me = electron_dos_mass(e_dos["a"][0], e_dos["ml"][0], e_dos["mm"][0], eg_zero, eg_T)
    h_coeff = {k: v[0] for k, v in h_dos.items() if k in ("a", "b", "c", "d", "e", "f", "g", "h", "i", "mm")}
    if "a" not in h_coeff:
        raise KeyError("hDOSMass.a")
    mh = hole_dos_mass(h_coeff, temperature_K)
    nc = dos_prefactor_cm3(temperature_K, me)
    nv = dos_prefactor_cm3(temperature_K, mh)
    d_eg0 = bandgap.get("dEg0(OldSlotboom)", [0.0])[0] if fold_old_slotboom else 0.0
    effective_gap = eg_T + d_eg0
    ni = intrinsic_density_cm3(nc, nv, effective_gap, temperature_K)
    result: Dict[str, Any] = {
        "bandgap_eV": eg_T,
        "electron_affinity_eV": bandgap["Chi0"][0],
        "conduction_band_density_of_states_cm3": nc,
        "valence_band_density_of_states_cm3": nv,
        "intrinsic_carrier_density_cm3": ni,
        "temperature_K": temperature_K,
        "derivation": {
            "Eg_T_eV": eg_T, "Eg_0_eV": eg_zero, "dEg0_OldSlotboom_folded_eV": d_eg0,
            "effective_gap_eV": effective_gap, "electron_dos_mass_ratio": me, "hole_dos_mass_ratio": mh,
            "kT_eV": KB_EV_PER_K * temperature_K,
            "dos_prefactor_cm3": dos_prefactor_cm3(temperature_K),
            "law": "ni = sqrt(Nc*Nv)*exp(-(Eg(T)+dEg0)/(2kT)); Nc,v = 2(2 pi m kB T/h^2)^1.5; Formula 1 masses",
        },
    }
    mobility = sections.get("ConstantMobility", {}).get("mumax")
    if mobility is not None:
        if len(mobility) != 2:
            raise ValueError("ConstantMobility.mumax must be an electron/hole pair")
        result["electron_mobility_cm2_per_V_s"] = mobility[0]
        result["hole_mobility_cm2_per_V_s"] = mobility[1]
    return result


def _formula(section: Dict[str, Any]) -> Optional[int]:
    for key in ("Formula", "formula"):
        if key in section and section[key]:
            return int(round(section[key][0]))
    return None


