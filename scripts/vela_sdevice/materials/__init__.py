def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _parse(path: Path) -> dict:
    if not path.is_file():
        raise MaterialsError("E303", name=path.name)
    try:
        return pir.parse_parameter_ir(path)
    except pir.ParParseError as problem:
        raise MaterialsError("E410", name=path.name, detail=str(problem)) from None
    except OSError as problem:
        raise MaterialsError("E410", name=path.name, detail=str(problem)) from None


def _sentaurus_names(vela_name: str) -> List[str]:
    names = [k for k, v in MATERIAL_MAP.items() if v == vela_name]
    proper = {"silicon": "Silicon", "si": "Si", "oxide": "Oxide", "sio2": "SiO2"}
    out = [proper.get(n, n) for n in names]
    if vela_name not in out:
        out.append(vela_name)
    return out


def _params_of(block: dict, origin: str) -> List[_Param]:
    formula = pmap._formula_of(block)
    out = []
    for item in block.get("parameters", []):
        if item.get("shadowed_by") is not None:
            continue
        out.append(_Param(
            section=block["section"], raw_name=item["raw_name"],
            base_name=item.get("base_name", item["raw_name"]), variant=item.get("variant"),
            values=list(item.get("values") or []), value_kind=item.get("value_kind", ""),
            origin=origin, scope_name=block["scope"].get("name"), source=dict(item.get("source", {})),
            formula=formula,
        ))
    return out


def _collect(ir: dict, kind: str, names: Optional[Iterable[str]], origin: str) -> Dict[str, List[_Param]]:
    """Merge active blocks of one scope kind into ``section -> params`` (last definition wins)."""
    wanted = None if names is None else {n.lower() for n in names}
    merged: Dict[str, Dict[Tuple[str, Optional[str]], _Param]] = {}
    for block in pir.active_blocks(ir):
        scope = block["scope"]
        if scope.get("kind") != kind:
            continue
        if wanted is not None and str(scope.get("name", "")).lower() not in wanted:
            continue
        if block.get("variant"):
            continue  # section variants (e.g. `Auger:high`) are not modelled
        target = merged.setdefault(block["section"], {})
        for param in _params_of(block, origin):
            target[param.key] = param
    return {section: list(params.values()) for section, params in merged.items()}


def _merge_layers(layers: Sequence[Dict[str, List[_Param]]]) -> Dict[str, Dict[Tuple[str, Optional[str]], _Param]]:
    """Per-parameter override: earlier layers win over later ones."""
    merged: Dict[str, Dict[Tuple[str, Optional[str]], _Param]] = {}
    for layer in layers:
        for section, params in layer.items():
            target = merged.setdefault(section, {})
            for param in params:
                target.setdefault(param.key, param)
    return merged


def _classify(param: _Param, models: Sequence[str]) -> pmap.Classification:
    return pmap.classify(param.section, param.base_name, param.variant, param.formula, models, param.values)


def _refine(param: _Param, classification: pmap.Classification, section_values: Dict[str, Any],
            ctx: _Context) -> Tuple[str, str, Optional[str]]:
    """Return ``(status, reason, refinement)`` after the emitter's inert/frozen rules."""
    status, reason = classification.status, classification.reason
    if status in (pmap.STATUS_EXACT, pmap.STATUS_FROZEN, pmap.STATUS_INACTIVE):
        return status, reason, None
    rule = _INERT_RULES.get((param.section, param.base_name))
    if rule is not None:
        why = rule(param.values, section_values, ctx)
        if why:
            return pmap.STATUS_EXACT, f"{status} in general; inert here: {why}", "inert"
    frozen = _FROZEN_RULES.get((param.section, param.base_name))
    if frozen is not None and status == pmap.STATUS_APPROXIMATED:
        return pmap.STATUS_FROZEN, frozen, "frozen"
    lossy = _LOSSY_RULES.get((param.section, param.base_name))
    if lossy is not None and status != pmap.STATUS_APPROXIMATED:
        return pmap.STATUS_APPROXIMATED, f"{status} in general; lossy here: {lossy}", "lossy"
    return status, reason, None


def _role_for(vela_name: str, sections: Dict[str, Any]) -> Optional[str]:
    role = KNOWN_ROLES.get(vela_name)
    if role is not None:
        return role
    if "Bandgap" in sections and "eDOSMass" in sections and "hDOSMass" in sections:
        return ROLE_TRANSPORT
    if "Epsilon" in sections:
        return ROLE_DIELECTRIC
    return None


def _split_target(target: str, carriers: int) -> List[str]:
    if "{carrier}" in target:
        return [target.replace("{carrier}", c) for c in ("electron", "hole")][:carriers]
    if " / " in target:
        first, second = [t.strip() for t in target.split(" / ", 1)]
        if not second.startswith("solver.") and not second.startswith("materials"):
            second = first.rsplit(".", 1)[0] + "." + second
        return [first, second][:carriers]
    return [target] * carriers


def _numbers(values: Sequence[Any]) -> List[float]:
    out = []
    for v in values:
        if isinstance(v, bool) or not isinstance(v, (int, float)):
            raise ValueError(f"non-numeric value {v!r}")
        out.append(float(v))
    return out


def emit_materials(par_path: Path, *, active_models: Sequence[str], temperature_K: float,
                   mesh_materials: Sequence[str], electrode_materials: Sequence[str] = (),
                   allow_lossy: bool = False, band_edge_sensitive: bool = False,
                   default_par: Optional[Path] = None, benchmark: Optional[str] = None,
                   effective_models: Optional[Sequence[dict]] = None) -> EmitResult:
    """Emit the C3 material file and the per-parameter report.

    ``active_models`` are mapping-matrix model names (see
    :func:`active_models_from_ir`); ``mesh_materials`` are the Vela names of
    the mesh regions' materials (C2 ``materials``); ``electrode_materials``
    are the Sentaurus names given by ``Electrode{ Material=... }`` whose
    ``Bandgap.WorkFunction`` WP4 needs.  ``band_edge_sensitive`` tells the
    emitter that absolute band edges are observable (gate/Schottky contacts or
    heterointerfaces), which keeps ``Bgn2Chi`` lossy instead of inert.
    """
    par_path = Path(par_path)
    default_par = Path(default_par) if default_par is not None else default_models_par_path()
    models = [pmap.MODEL_ALIASES.get(m, m) for m in active_models]
    model_set = set(models)
    ctx = _Context(temperature_K=float(temperature_K), active_models=model_set,
                   band_edge_sensitive=bool(band_edge_sensitive))

    user_ir = _parse(par_path)
    default_ir = _parse(default_par) if default_par.exists() else {"blocks": [], "files": []}
    user_global = _collect(user_ir, "global", None, "user_global")

    report: Dict[str, Any] = {
        "schema": REPORT_SCHEMA_ID,
        "parameter_file": {"path": par_path.name, "sha256": _sha256(par_path), "files": user_ir.get("files", [])},
        "default_library": {"path": default_par.as_posix(),
                            "sha256": _sha256(default_par) if default_par.exists() else None},
        "temperature_K": ctx.temperature_K,
        "active_models": sorted(model_set),
        "effective_models": list(effective_models or []),
        "allow_lossy": bool(allow_lossy),
        "band_edge_sensitive": ctx.band_edge_sensitive,
        "constants": dict(CONSTANTS),
        "materials": [],
        "solver_parameters": [],
        "electrodes": [],
        "lossy": [],
        "inert": [],
        "blocking": [],
        "ignored_scopes": [],
        "counts": {},
    }
    counts: Dict[str, int] = {}

    def tally(status: str) -> None:
        counts[status] = counts.get(status, 0) + 1

    # Region / interface scopes cannot be represented; active parameters there are fatal.
    for block in pir.active_blocks(user_ir):
        kind = block["scope"].get("kind")
        if kind in ("global", "material"):
            continue
        entry = {"kind": kind, "name": block["scope"].get("name"), "section": block["section"],
                 "line": block.get("source_span", {}).get("line")}
        for param in _params_of(block, f"user_{kind}"):
            classification = _classify(param, models)
            if classification.status != pmap.STATUS_INACTIVE:
                path = f"{kind}:{param.scope_name}.{param.section}.{param.raw_name}"
                raise MaterialsError("E404", path=path,
                                     model=classification.entry.requires_model if classification.entry
                                     and classification.entry.requires_model else pmap.SECTION_MODELS.get(
                                         param.section, param.section),
                                     status="unsupported_scope")
        report["ignored_scopes"].append(entry)

    used_scopes: set = set()
    materials_out: List[dict] = []
    for vela_name in list(dict.fromkeys(mesh_materials)):
        names = _sentaurus_names(vela_name)
        user_material = _collect(user_ir, "material", names, "user_material")
        default_material = _collect(default_ir, "material", names, "vela_default")
        used_scopes.update(n.lower() for n in names)
        merged = _merge_layers([user_material, user_global, default_material])
        if not user_material and not default_material:
            raise MaterialsError("E403", name=vela_name)
        role = _role_for(vela_name, merged)
        if role is None:
            raise MaterialsError("E403", name=vela_name)
        material_report: Dict[str, Any] = {
            "name": vela_name, "role": role, "sentaurus_scopes": names,
            "defined_in_parameter_file": bool(user_material),
            "sections": {}, "parameters": [], "derivation": None,
        }
        sections_numeric: Dict[str, Dict[str, Any]] = {}
        relevant_sections = set(MATERIAL_SECTIONS)
        if role != ROLE_DIELECTRIC:
            for model, section in MODEL_SECTIONS.items():
                if model in model_set:
                    if section not in merged:
                        raise MaterialsError("E404", path=f"{vela_name}.{section}", model=model,
                                             status="missing_section")
                    relevant_sections.add(section)
        for section, params in merged.items():
            section_values = {p.raw_name: p.values for p in params.values()}
            numeric: Dict[str, Any] = {}
            for param in params.values():
                classification = _classify(param, models)
                status, reason, refinement = _refine(param, classification, section_values, ctx)
                record = {
                    "section": section, "parameter": param.raw_name, "variant": param.variant,
                    "formula": param.formula, "values": param.values, "origin": param.origin,
                    "scope": param.scope_name, "source": param.source,
                    "status": status, "matrix_status": classification.status,
                    "target": classification.entry.target if classification.entry else None,
                    "requires_model": classification.entry.requires_model if classification.entry else None,
                    "reason": reason,
                }
                material_report["parameters"].append(record)
                tally(status)
                if refinement == "inert":
                    report["inert"].append({**record, "material": vela_name})
                if status == pmap.STATUS_INACTIVE:
                    continue
                model_name = (classification.entry.requires_model if classification.entry
                              and classification.entry.requires_model
                              else pmap.SECTION_MODELS.get(section, section))
                path = f"{vela_name}.{section}.{param.raw_name}"
                if status == pmap.STATUS_APPROXIMATED:
                    if not allow_lossy:
                        raise MaterialsError("E404", path=path, model=model_name, status=status)
                    report["lossy"].append({**record, "material": vela_name})
                elif status not in (pmap.STATUS_EXACT, pmap.STATUS_FROZEN):
                    raise MaterialsError("E404", path=path, model=model_name, status=status)
                if section in relevant_sections:
                    numeric[param.raw_name] = param.values
                    if classification.entry and classification.entry.target and \
                            classification.entry.target.startswith("solver."):
                        _route_solver_parameter(report, vela_name, section, param, classification.entry.target,
                                                status, ctx.temperature_K)
            if section in relevant_sections:
                sections_numeric[section] = numeric
                material_report["sections"][section] = {
                    "origins": sorted({p.origin for p in params.values()}),
                    "parameters": len(params),
                }
        entry = _emit_material_entry(vela_name, role, sections_numeric, ctx, model_set, material_report,
                                     par_path, report)
        materials_out.append(entry)
        report["materials"].append(material_report)

    for scope_name in sorted({str(b["scope"].get("name")) for b in pir.active_blocks(user_ir)
                              if b["scope"].get("kind") == "material"}):
        if scope_name.lower() not in used_scopes and map_material(scope_name).lower() not in used_scopes:
            report["ignored_scopes"].append({"kind": "material", "name": scope_name, "section": None,
                                             "line": None, "reason": "not present in the mesh"})

    for electrode_material in list(dict.fromkeys(electrode_materials)):
        report["electrodes"].append(_electrode_entry(electrode_material, user_ir, default_ir, user_global))

    report["counts"] = dict(sorted(counts.items()))
    materials = {
        "schema": SCHEMA_ID,
        "benchmark": benchmark or f"sdevice:{par_path.stem}",
        "revision": 1,
        "unit_system": dict(UNIT_SYSTEM),
        "materials": materials_out,
    }
    return EmitResult(materials=materials, report=report)


def _route_solver_parameter(report: dict, material: str, section: str, param: _Param, target: str,
                            status: str, temperature_K: float) -> None:
    units = _SI_FACTORS.get((section, param.base_name))
    if units is None:
        raise MaterialsError("E404", path=f"{material}.{section}.{param.raw_name}",
                             model=pmap.SECTION_MODELS.get(section, section), status="unit_unmapped")
    unit_par, unit_si, factor = units
    values = _numbers(param.values)
    targets = _split_target(target, len(values))
    carriers = ["electron", "hole"] if len(values) == 2 else [None]
    for value, path, carrier in zip(values, targets, carriers):
        report["solver_parameters"].append({
            "material": material, "section": section, "parameter": param.raw_name, "variant": param.variant,
            "carrier": carrier, "target": path, "value_par": value, "unit_par": unit_par,
            "value_si": value * factor, "unit_si": unit_si, "status": status, "origin": param.origin,
            "source": param.source,
        })
    if section == "Auger":
        _finish_auger(report, material, temperature_K)


def _finish_auger(report: dict, material: str, temperature_K: float) -> None:
    rows = [r for r in report["solver_parameters"] if r["material"] == material and r["section"] == "Auger"
            and r["parameter"] in ("A", "B", "C")]
    if len(rows) != 6:
        return
    report["solver_parameters"] = [r for r in report["solver_parameters"]
                                   if not (r["material"] == material and r["section"] == "Auger"
                                           and r["parameter"] == "A+B(T/300)+C(T/300)^2")]
    ratio = temperature_K / _REFERENCE_T
    for carrier, target in (("electron", "solver.auger_cn_m6_per_s"), ("hole", "solver.auger_cp_m6_per_s")):
        by_name = {r["parameter"]: r for r in rows if r["carrier"] == carrier}
        value_si = by_name["A"]["value_si"] + by_name["B"]["value_si"] * ratio + by_name["C"]["value_si"] * ratio ** 2
        report["solver_parameters"].append({
            "material": material, "section": "Auger", "parameter": "A+B(T/300)+C(T/300)^2", "variant": None,
            "carrier": carrier, "target": target, "value_par": value_si / 1.0e-12, "unit_par": "cm^6/s",
            "value_si": value_si, "unit_si": "m^6/s", "status": pmap.STATUS_FROZEN,
            "origin": by_name["A"]["origin"], "source": by_name["A"]["source"],
        })


def _emit_material_entry(vela_name: str, role: str, sections: Dict[str, Dict[str, Any]], ctx: _Context,
                         model_set: set, material_report: dict, par_path: Path, report: dict) -> dict:
    epsilon = sections.get("Epsilon", {}).get("epsilon")
    if not epsilon:
        raise MaterialsError("E404", path=f"{vela_name}.Epsilon.epsilon", model="Poisson", status="missing_parameter")
    origins = sorted({o for s in material_report["sections"].values() for o in s["origins"]})
    provenance = (f"{'/'.join(material_report['sentaurus_scopes'])} from {par_path.name} "
                  f"(sha256 {report['parameter_file']['sha256'][:12]}) at {ctx.temperature_K:g} K; "
                  f"origins {','.join(origins)}")
    entry: Dict[str, Any] = {"name": vela_name, "role": role, "eps_r": float(epsilon[0])}
    if role == ROLE_DIELECTRIC:
        bandgap = sections.get("Bandgap", {})
        if "Eg0" in bandgap and "alpha" in bandgap and "beta" in bandgap and "Tpar" in bandgap:
            eg_T, _ = varshni_gap(bandgap["Eg0"][0], bandgap["alpha"][0], bandgap["beta"][0],
                                  bandgap["Tpar"][0], ctx.temperature_K)
            entry["bandgap_eV"] = eg_T
        if "Chi0" in bandgap:
            entry["electron_affinity_eV"] = float(bandgap["Chi0"][0])
        entry["temperature_K"] = ctx.temperature_K
        entry["provenance"] = provenance + "; dielectric: Epsilon" + (
            "/Bandgap" if "bandgap_eV" in entry else "")
        material_report["derivation"] = {"role": role, "bandgap_eV": entry.get("bandgap_eV")}
        return entry
    try:
        values = evaluate_semiconductor(sections, ctx.temperature_K, "OldSlotboom" in model_set)
    except KeyError as missing:
        raise MaterialsError("E404", path=f"{vela_name}.{missing.args[0]}", model="Poisson",
                             status="missing_parameter") from None
    except ValueError as problem:
        raise MaterialsError("E404", path=f"{vela_name}.eDOSMass/hDOSMass", model="Poisson",
                             status=f"unsupported_formula ({problem})") from None
    if role == ROLE_TRANSPORT and "electron_mobility_cm2_per_V_s" not in values:
        raise MaterialsError("E404", path=f"{vela_name}.ConstantMobility.mumax", model="ConstantMobility",
                             status="missing_parameter")
    derivation = values.pop("derivation")
    entry.update(values)
    quantum = sections.get("QuantumPotentialParameters", {}).get("gamma")
    if quantum and "eQuantumPotential" in model_set:
        entry["electron_quantum_gamma"] = float(quantum[0])
    entry["provenance"] = (provenance + "; Epsilon/Bandgap/eDOSMass Formula 1/hDOSMass Formula 1"
                           + ("/ConstantMobility" if "electron_mobility_cm2_per_V_s" in entry else "")
                           + f"; {derivation['law']}"
                           + (f"; dEg0(OldSlotboom)={derivation['dEg0_OldSlotboom_folded_eV']:g} eV folded into ni"
                              if derivation["dEg0_OldSlotboom_folded_eV"] else "; no bandgap narrowing folded")
                           + "; CODATA 2018 constants")
    material_report["derivation"] = derivation
    return entry


def _electrode_entry(material: str, user_ir: dict, default_ir: dict, user_global: Dict[str, List[_Param]]) -> dict:
    names = _sentaurus_names(map_material(material))
    if material not in names:
        names.append(material)
    layers = [_collect(user_ir, "material", names, "user_material"), user_global,
              _collect(default_ir, "material", names, "vela_default")]
    if not layers[0] and not layers[2]:
        raise MaterialsError("E403", name=material)
    merged = _merge_layers(layers)
    work_function = merged.get("Bandgap", {}).get(("WorkFunction", None))
    if work_function is None or not work_function.values:
        raise MaterialsError("E404", path=f"{material}.Bandgap.WorkFunction", model="Electrode",
                             status="missing_parameter")
    return {"material": material, "work_function_eV": float(work_function.values[0]),
            "origin": work_function.origin, "source": work_function.source}


def write_materials(out_dir: Path, result: EmitResult) -> Tuple[Path, Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    materials_path = out_dir / "materials.json"
    report_path = out_dir / "materials_report.json"
    materials_path.write_text(json.dumps(result.materials, indent=2) + "\n", encoding="utf-8")
    report_path.write_text(json.dumps(result.report, indent=2) + "\n", encoding="utf-8")
    return materials_path, report_path
