"""Materials emitter for ``vela device`` (WP3, contract C3).

Turns a Sentaurus ``.par`` parameter file into the role-based Vela material
file (``schemas/vela.templates_ldmos.materials.v1.schema.json``) plus a
per-parameter report, driven by the models the execution IR (C1) proved to be
active and by the material set of the imported mesh (C2).

Design
======

* Syntax is delegated to ``scripts/sentaurus_parameter_ir.py`` and the
  fidelity verdict of every parameter to the mapping matrix in
  ``scripts/sentaurus_parameter_map.py``.  This module only *evaluates* the
  frozen laws (Varshni gap, Formula 1 density-of-states masses, ``ni``) and
  *routes* the results into the C3 fields.
* ``share/vela/materials/models.par`` (generated by
  ``scripts/generate_default_models_par.py`` from the C++ built-ins) is the
  default library: sections a user file does not define fall back to it,
  parameter by parameter, and every fallback is recorded with
  ``origin = "vela_default"``.  A mesh material that neither file defines is
  fatal (E403) -- Vela cannot substitute Sentaurus' proprietary defaults.
* Fail closed: ``unsupported_*``/``unmapped`` parameters of an active model,
  active parameters in region/interface scopes, and missing sections of an
  active model are fatal (E404).  ``approximated`` parameters are fatal unless
  ``allow_lossy`` is set, in which case they are written and listed under
  ``report["lossy"]``.  A small refinement table demotes matrix rows whose
  effect provably vanishes for the emitted contract (for example a
  temperature exponent at the reference temperature); every demotion is
  listed under ``report["inert"]`` with its reason.

Physical constants are CODATA 2018 and identical to
``include/vela/core/PhysicalConstants.h``; the density-of-states prefactor is
the full ``2 (2 pi m0 kB T / h^2)^{3/2}`` expression documented in the
parameter files, not the rounded ``2.5094e19`` that appears in their comments.
"""

