def active_models_from_ir(ir: dict) -> List[str]:
    """Map C1 ``physics.effective[].key`` entries onto mapping-matrix model names."""
    models: set[str] = set()
    for item in ir.get("physics", {}).get("effective", []):
        key = str(item["key"])
        params = item.get("parameters") or {}
        head, _, tail = key.partition(".")
        if head == "Mobility":
            name = tail
            if name in ("eHighFieldSaturation", "hHighFieldSaturation"):
                name = "HighFieldSaturation"
            models.add(name)
            if name == "Enormal":
                models.add("EnormalDependence")
        elif key == "Recombination.SRH":
            models.add("SRH")
            if params.get("temperature_dependence"):
                models.add("TempDependence")
        elif key == "Recombination.Avalanche":
            raw = str(params.get("model", "VanOverstraeten"))
            models.add(_AVALANCHE_MODELS.get(raw.lower(), raw))
        elif key == "Recombination.Band2Band":
            models.add("Band2BandTunneling")
        elif head in ("Recombination", "EffectiveIntrinsicDensity") and tail:
            models.add(tail)
        else:
            models.add(key)
    return sorted(models)


