@dataclass
class _Context:
    temperature_K: float
    active_models: set
    band_edge_sensitive: bool


def _all(values: Sequence[Any], target: float) -> bool:
    return bool(values) and all(isinstance(v, (int, float)) and not isinstance(v, bool)
                                and abs(float(v) - target) <= 1.0e-12 for v in values)


def _at_reference_temperature(ctx: _Context) -> bool:
    return abs(ctx.temperature_K - _REFERENCE_T) <= _T_TOL


_BGN_MODELS = ("OldSlotboom", "Slotboom", "Bennett", "delAlamo", "BandGapNarrowing")


def _bgn_active(ctx: _Context) -> bool:
    return any(m in ctx.active_models for m in _BGN_MODELS)


#: (section, parameter) -> predicate(values, section_parameters, ctx) -> reason or None.
